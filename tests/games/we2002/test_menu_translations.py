def test_the_three_languages_translate_the_same_set_of_strings():
    keys = {lang: set(d) for lang, d in _TRANSLATIONS.items()}
    assert set(keys) == {"es", "fr", "pt"}
    assert keys["es"] == keys["fr"] == keys["pt"]


def test_every_pinned_string_is_translated_within_its_field():
    for text, width in _WIDTHS.items():
        for lang, d in _TRANSLATIONS.items():
            assert text in d, (lang, text)
            assert len(d[text]) <= width, (lang, text, d[text], width)
            assert d[text].isascii(), (lang, text)


def test_a_record_keeps_its_width_and_terminator():
    record = b"OV.NEAR\x00"
    for lang in ("es", "fr", "pt"):
        out = _translate_record(record, _TRANSLATIONS[lang])
        assert len(out) == len(record) and out.endswith(b"\x00")
        assert out[:-1].decode("ascii").strip() == _TRANSLATIONS[lang]["OV.NEAR"]


def test_an_unknown_string_passes_through_unchanged():
    assert _translate_record(b"ZZZ\x00", _TRANSLATIONS["pt"]) == b"ZZZ\x00"
